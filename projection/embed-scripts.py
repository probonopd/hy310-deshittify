#!/usr/bin/env python3
"""Turn scripts/*.sh into string resources (script_<name>) that the app writes to its files directory at startup.
Run by build.sh; the generated src/res/values/scripts.xml is committed so a plain apktool build also works."""
import glob, os, sys
here = os.path.dirname(os.path.abspath(__file__))
out = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- generated by embed-scripts.py from scripts/*.sh, do not edit -->', '<resources>']
for path in sorted(glob.glob(os.path.join(here, "scripts", "*.sh"))):
    name = "script_" + os.path.basename(path)[:-3]
    text = open(path).read()
    esc = (text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
           .replace('"', '\\"').replace("'", "\\'").replace("@", "\\@").replace("?", "\\?").replace("\n", "\\n"))
    out.append(f'    <string name="{name}" formatted="false">"{esc}"</string>')
out.append("</resources>")
open(os.path.join(here, "src", "res", "values", "scripts.xml"), "w").write("\n".join(out) + "\n")
